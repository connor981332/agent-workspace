BEGIN = '<!-- agent-workspace:begin (generated by aw instructions; edit workspace.toml instead) -->'
END = '<!-- agent-workspace:end -->'
FIND_HOOK = ('d="${CLAUDE_PROJECT_DIR:-$PWD}"; while [ "$d" != / ] && [ ! -f "$d/bin/aw" ]; do d=$(dirname "$d"); done; '
             '[ ! -f "$d/bin/aw" ] || "$d/bin/aw" hook ')
GITIGNORE = ['/.lane', '/.lanes/', '/.worktrees/', '__pycache__/']
CLAUDE_MATCHER = 'Bash|Edit|Write|MultiEdit|NotebookEdit|Read|Grep|Glob|run_terminal_command|read_file|write|search_replace|grep'


def claude_hooks():
    command_for = lambda event: {'hooks': [{'type': 'command', 'command': FIND_HOOK + event}]}
    return {'hooks': {'SessionStart': [command_for('session-start')],
                      'PreToolUse': [{'matcher': CLAUDE_MATCHER, **command_for('pre-tool-use')}],
                      'SessionEnd': [command_for('session-end')]}}


def codex_hooks():
    data = claude_hooks()
    data['hooks']['PreToolUse'][0]['matcher'] = 'Bash|apply_patch'
    return data


def rendered(data):
    return json.dumps(data, indent=2) + '\n'


def write_hooks(root, check=False):
    """Merge into existing settings: only the hooks key belongs to this tool."""
    stale = []
    for name, data in (('.claude/settings.json', claude_hooks()), ('.codex/hooks.json', codex_hooks())):
        path = Path(root) / name
        current = json.loads(path.read_text()) if path.exists() else {}
        merged = {**current, **data}
        if current != merged:
            stale.append(name)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(rendered(merged))
    if check and stale:
        print('Stale hook configuration: ' + ', '.join(stale) + '. Run bin/aw hooks-config.', file=sys.stderr)
        return 1
    return 0


def instruction_block(context):
    manifest = context.manifest
    rows = '\n'.join(f'| `{p.alias}` | `{p.directory}` | {p.runner} | '
                     + (f'{p.server.port} + {context.settings["port_stride"]} × slot' if p.server else 'none') + ' |'
                     for p in manifest.projects.values())
    tasks = ''.join(f'- `bin/aw task {t.name}`: {t.description or "see workspace.toml"}\n' for t in manifest.tasks.values())
    return f"""{BEGIN}
## Agent lanes

This workspace runs parallel agents in isolated **lanes**. A lane is `{context.lanes.name}/<n>/`: worktrees of every
repository, its own lane state, and whatever its setup scripts create. Hooks enforce the path rules
below where the harness supports them. They are guardrails, not a sandbox, so a harness without
hooks must follow the same rules.

**Before editing, determine your lane.** If the root has a `.lane` file, stay in that lane.
Otherwise run `bin/aw attach` (`--harness codex` or `--harness grok` for those harnesses) before
changing files or Git state. Read-only work needs no lane. Never attach twice, and never start
another agent.

After attaching, start **every shell command** with `cd <absolute-lane-path> &&` and use absolute
lane paths for file tools. `bin/aw whoami` reports your lane, heads, slot, URLs and logs without
changing anything.

| Project | Directory | Runner | Server port |
|---|---|---|---|
{rows}

- Run project commands with `bin/aw run <project> <command>`.
- Servers need a slot. Run `bin/aw serve [<project>...]` in the background; it queues when slots are
  busy. Return the slot with `bin/aw stop`. Slots also expire after
  {context.settings['slot_idle_minutes']} idle minutes. Never start servers another way.
- Do not kill shared processes, and do not manage shared containers yourself.
- Hand off verified work with `bin/aw finish --plan plans/<name>.md --summary "<one line>"`, or
  `--no-plan`. It needs clean committed work with exact pushed heads and open merge requests.
  Add `--delivery local --reason "..."` only when the owner explicitly wants local review.
- Never release your own lane, and never delete lane state to make something look clean. A gone
  remote branch, a handoff or a quiet session does not prove that work merged. Uncertain work stays
  protected.
- Owner-only commands are blocked for agents: `new`, `resume`, `delete`, `open`, `containers`,
  `mine`, `init`, `sweep --apply` and maintenance. The owner can delegate maintenance for a limited
  time with `bin/aw delegate`; agents never grant it.
{'' if not tasks else chr(10) + 'Workspace tasks:' + chr(10) + chr(10) + tasks}{END}
"""


def write_instructions(context, check=False):
    path = context.root / 'AGENTS.md'
    block = instruction_block(context)
    text = path.read_text() if path.exists() else f'# {context.manifest.name}\n\n'
    if BEGIN in text and END in text:
        before, rest = text.split(BEGIN, 1)
        after = rest.split(END, 1)[1].removeprefix('\n')
        updated = before + block + after
    else:
        updated = text.rstrip() + '\n\n' + block
    if check:
        if updated != text:
            print('AGENTS.md instructions are stale; run bin/aw instructions.', file=sys.stderr)
            return 1
        return 0
    path.write_text(updated)
    claude = context.root / 'CLAUDE.md'
    if not claude.exists():
        claude.write_text('@AGENTS.md\n')
    return 0


def install_launcher(root):
    target = Path(root) / 'bin/aw'
    target.parent.mkdir(exist_ok=True)
    shutil.copyfile(Path(__file__).with_name('launcher.py'), target)
    target.chmod(target.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def ensure_gitignore(root, entries):
    path = Path(root) / '.gitignore'
    lines = path.read_text().splitlines() if path.exists() else []
    missing = [e for e in entries if e not in lines]
    if missing:
        path.write_text('\n'.join([*lines, *missing]) + '\n')


def template(name, namespace, projects, base, source, ref, subdir):
    if ref:
        tool = f'[tool]\nsource = "{source}"\nref = "{ref}"\nsubdir = "{subdir}"\n'
    else:
        tool = ('[tool]\n# Pin the tool: a Git URL, a full commit SHA, and the subdirectory holding pyproject.toml.\n'
                f'# source = "{source}"\n# ref = "<full commit sha>"\n# subdir = "{subdir}"\n')
    if projects:
        tables = ''.join(f'\n[projects.{alias}]\ndirectory = "{directory}"\n# repo = "git@example.com:org/{directory}.git"\n'
                         f'# base = "origin/main"\n# install = ["npm", "ci"]\n# install_stamp = "package-lock.json"\n'
                         f'# generated = ["node_modules/"]\n\n# [projects.{alias}.server]\n# command = "exec npm run dev"\n'
                         f'# port = {4000 + 10 * index}   # Base port; a server in slot k uses base + 100 * k.\n# env = {{ PORT = "{{port}}" }}\n'
                         for index, (alias, directory) in enumerate(projects))
    else:
        tables = ('\n# This repository is the only project.\n[projects.app]\ndirectory = "."\n# install = ["npm", "ci"]\n'
                  '# install_stamp = "package-lock.json"\n# generated = ["node_modules/"]\n\n# [projects.app.server]\n'
                  '# command = "exec npm run dev"\n# port = 4000   # Base port; a server in slot k uses base + 100 * k.\n'
                  '# env = { PORT = "{port}" }\n')
    return f"""# Agent Workspace configuration. Reference: docs/manifest.md in the tool.
[workspace]
name = "{name}"
namespace = "{namespace}"   # Prefixes state, Git metadata and settings; unique per machine is safest.
forge = "auto"              # auto, github, gitlab or none. Decides how merges are proved.

[lanes]
slots = 2                   # How many lanes may run servers at once.
workspace_base = "{base}"

{tool}{tables}"""


def init_command(argv):
    parser = argparse.ArgumentParser(prog='aw init', description='Add Agent Workspace to this Git repository')
    parser.add_argument('--name')
    parser.add_argument('--namespace', default='aw')
    parser.add_argument('--project', action='append', default=[], metavar='ALIAS=DIRECTORY',
                        help='A nested repository. Omit for a single-repository workspace.')
    parser.add_argument('--tool-source', default='https://github.com/connor981332/agent-workspace.git')
    parser.add_argument('--tool-ref', default='')
    parser.add_argument('--tool-subdir', default='workspace-candidate-1')
    args = parser.parse_args(argv)
    root = Path.cwd().resolve()
    if not (root / '.git').is_dir():
        raise ValueError('Run aw init at the top of a Git repository (not inside a worktree)')
    if (root / '.lane').exists():
        raise ValueError('aw init runs in the owner checkout, not in a lane')
    if not manifest_module.NAMESPACE.fullmatch(args.namespace):
        raise ValueError('--namespace must be 1-16 lowercase letters or digits')
    projects = []
    for item in args.project:
        alias, separator, directory = item.partition('=')
        if not separator:
            raise ValueError('--project takes ALIAS=DIRECTORY')
        projects.append((alias, directory))
    base = value(root, 'symbolic-ref', '--quiet', '--short', 'HEAD') or 'main'
    path = root / manifest_module.NAME
    if path.exists():
        print(f'{manifest_module.NAME} exists; keeping it.')
    else:
        path.write_text(template(args.name or root.name, args.namespace, projects, base,
                                 args.tool_source, args.tool_ref, args.tool_subdir))
    install_launcher(root)
    ensure_gitignore(root, [*GITIGNORE, *(f'/{d}/' for _, d in projects)])
    write_hooks(root)
    context = Context.discover(root)
    write_instructions(context)
    print(f'Initialized {root}.\nNext: review {manifest_module.NAME}, commit these files, then run bin/aw bootstrap.')
    return 0


def bootstrap(context):
    if context.caller:
        raise ValueError('bin/aw bootstrap runs in the owner checkout, not in a lane')
    todo = 0
    for project in context.manifest.projects.values():
        if not project.nested:
            continue
        path = context.main / project.directory
        if (path / '.git').exists():
            print(f'{project.directory}: already cloned')
        elif project.repo:
            result = subprocess.run(['git', 'clone', project.repo, str(path)])
            if result.returncode:
                raise ValueError(f'Could not clone {project.repo}')
        else:
            print(f'{project.directory}: missing, and workspace.toml names no repo for it')
            todo = 1
    hooks = context.main / '.githooks'
    if hooks.is_dir():
        for repo in (context.main, *(context.main / d for d, _ in context.nested_projects)):
            if (repo / '.git').exists():
                command(['git', '-C', repo, 'config', 'core.hooksPath', hooks])
    if not value(context.main, 'config', 'user.email') or not value(context.main, 'config', 'user.name'):
        print('Git has no author identity: set git config --global user.name and user.email.')
        todo = 1
    if context.manifest.prepare or context.manifest.setup or context.manifest.teardown:
        print('Lifecycle scripts run from each lane; bin/aw doctor checks that they exist.')
    if health(context) != 'active' and not todo:
        activate(context)
        print('Activated lanes for this checkout.')
    report = doctor(context)
    print_doctor(report)
    return 0 if report['ok'] and not todo else 1


def doctor(context):
    """Read-only. Every failed check names its fix."""
    rows = []

    def check(name, passed, fix=''):
        rows.append(dict(check=name, ok=bool(passed), fix='' if passed else fix))

    manifest = context.manifest
    check('Python 3.11 or newer', sys.version_info >= (3, 11), 'Install Python 3.11+')
    check('git available', shutil.which('git'), 'Install git')
    check('Checkout activated', health(context) == 'active', 'bin/aw bootstrap')
    check('bin/aw present', (context.root / 'bin/aw').is_file(), 'aw init')
    check('Lanes directory ignored', not command(['git', '-C', context.main, 'check-ignore', '-q', str(context.lanes) + '/']).returncode,
          f'Add /{context.lanes.name}/ to .gitignore')
    for name in ('.claude/settings.json', '.codex/hooks.json'):
        try:
            hooks = json.loads((context.root / name).read_text()).get('hooks', {})
        except (OSError, ValueError):
            hooks = {}
        commands = [h.get('command', '') for rows in hooks.values() for row in rows for h in row.get('hooks', [])]
        check(f'{name} routes to bin/aw', any('"$d/bin/aw" hook pre-tool-use' in c for c in commands), 'bin/aw hooks-config')
    for project in manifest.projects.values():
        if project.nested:
            check(f'{project.alias}: repository cloned', (context.main / project.directory / '.git').exists(), 'bin/aw bootstrap')
    if any(p.runner == 'docker' for p in manifest.projects.values()):
        check('docker available', shutil.which('docker'), 'Install Docker')
        check('compose file present', manifest.compose_file and (context.root / manifest.compose_file).is_file(),
              'Set docker.compose_file in workspace.toml')
    for label, words in (('prepare', manifest.prepare), ('setup', manifest.setup), ('teardown', manifest.teardown),
                         *((f'task {t.name}', t.command) for t in manifest.tasks.values())):
        if words and '/' in words[0]:
            target = context.root / words[0]
            check(f'{label} script is executable', target.is_file() and os.access(target, os.X_OK),
                  f'Create {words[0]} and make it executable')
    for setting in (context.settings['workspace_base'],):
        check(f'Workspace base {setting} resolves', value(context.main, 'rev-parse', '--verify', setting + '^{commit}'),
              'Set lanes.workspace_base in workspace.toml')
    for alias, (directory, base) in context.bases.items():
        if alias == 'workspace' or not (context.main / directory / '.git').exists():
            continue
        check(f'{alias}: base {base} resolves', value(context.main / directory, 'rev-parse', '--verify', base + '^{commit}'),
              f'Fetch the project, or set projects.{alias}.base')
    seen = set()
    for alias, (directory, _) in context.bases.items():
        url = value(context.main / directory, 'remote', 'get-url', 'origin')
        identity = remote_identity(url)
        forge = for_identity(manifest.forge, identity, lambda: 0)
        if forge and forge.binary not in seen:
            seen.add(forge.binary)
            check(f'{forge.binary} available for merge proof', shutil.which(forge.binary),
                  f'Install {forge.binary}. Without it, squash merges cannot be proved and those lanes are kept.')
    return dict(schema_version=1, ok=all(r['ok'] for r in rows), checks=rows)


def print_doctor(report):
    for row in report['checks']:
        print(('ok   ' if row['ok'] else 'FAIL ') + row['check'] + (f"  -> {row['fix']}" if row['fix'] else ''))
    print('All checks passed.' if report['ok'] else 'Some checks failed.')
