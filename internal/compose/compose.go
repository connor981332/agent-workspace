const (
	// TeamPath is the team layer's instructions, committed in the workspace repository.
	TeamPath = ".aw/instructions.md"
	// AgentsPath is the canonical instructions file, which holds the generated block.
	AgentsPath = "AGENTS.md"
	// ClaudePath is Claude Code's own file. aw does not create it: Claude Code reads AGENTS.md itself.
	// When the file exists, Claude Code reads it instead of AGENTS.md, so it must import AGENTS.md.
	ClaudePath = "CLAUDE.md"
	// ClaudeImport is the line that imports it.
	ClaudeImport = "@AGENTS.md"
	// PersonalPath is Claude Code's personal file. It is excluded from Git, never committed.
	PersonalPath = "CLAUDE.local.md"
	managedPath  = ".aw/managed"
	managedKey   = AgentsPath + "#aw-block"

	begin = "<!-- aw:begin (generated by aw setup; change .aw/instructions.md instead) -->"
	end   = "<!-- aw:end -->"
)

// framework is the framework layer: how to work in any workspace.
const framework = `## Working in this workspace

This workspace runs several agents in parallel, each in its own lane.

- The checkout you start in belongs to the human. Reading needs nothing, here or from a lane. Before changing anything, run ` + "`bin/aw attach \"<what you are working on>\"`" + ` and work in the lane root it prints.
- If your working directory stays where it was, start each shell command with ` + "`cd <lane root> &&`" + ` and use absolute paths inside the lane for file tools.
- ` + "`bin/aw lanes`" + ` lists the lanes, and ` + "`bin/aw whoami`" + ` shows where you are. ` + "`bin/aw run <project> <command>`" + ` runs a command with the lane's environment.
- Once you are in a lane, paths these instructions name, such as a ` + "`scratch/`" + ` directory, mean your lane root's copy, not the owner checkout's.
- A repository that is not a project of this workspace can be cloned into your lane, for example under its ` + "`scratch/`" + `; aw's guards and hooks do not cover it, and its own conventions apply.
- When you stop, or hand the work off for review with merge requests still open, run ` + "`bin/aw finish`" + ` so that the next session can pick up the work.
- When aw refuses something, its message says what to do instead.`

// publishing is added when the publication safeguard is on, and carefully is added with any safeguard:
// without them aw has no opinion about either.
const publishing = `- To publish a lane's work, run these from the project's worktree: ` + "`git push -u origin HEAD`" + `, then ` + "`gh pr create`" + ` or ` + "`glab mr create`" + `. To comment on or merge the lane's own merge request, name no number (` + "`gh pr merge`" + `, ` + "`glab mr merge`" + `), so that it means this lane's branch. Where the workspace pre-authorizes publishing, these need no approval.`

const carefully = ` If the human asked for this work, ask them to approve it and carry on. Do not stop at the refusal, and do not reach the same result by another route.`

// Result says what aw setup did to one file.
type Result struct {
	Path    string `json:"path"`
	Changed bool   `json:"changed"`
	// Edited: the generated block was changed by hand, so it was left as it is.
	Edited bool   `json:"edited,omitempty"`
	Note   string `json:"note,omitempty"`
}

// EditedNote tells the human what to do about a generated block changed by hand.
const EditedNote = "the generated block in AGENTS.md was edited by hand, so aw left it alone → move the change to .aw/instructions.md, delete the block from <!-- aw:begin to <!-- aw:end -->, and run aw setup"

func sum(s string) string {
	b := sha256.Sum256([]byte(s))
	return hex.EncodeToString(b[:])
}

// body is the generated block's content.
func body(owner string) (string, error) {
	team, err := os.ReadFile(filepath.Join(owner, TeamPath))
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return "", err
	}
	text := framework
	if c, err := config.Load(owner); err == nil && len(c.Safeguards.Enable) > 0 {
		text += carefully
		if slices.Contains(c.Safeguards.Enable, "publication") {
			text += "\n" + publishing
		}
	}
	if t := strings.TrimSpace(string(team)); t != "" {
		text += "\n\n" + t
	}
	return text, nil
}

// findBlock locates the block in text. found is false when it has none; a block with only one of
// its markers, or with them reversed, is an error, since replacing it could lose what lies between.
func findBlock(text, path string) (before, inner, after string, found bool, err error) {
	b, e := strings.Index(text, begin), strings.Index(text, end)
	switch {
	case b < 0 && e < 0:
		return "", "", "", false, nil
	case b < 0 || e < b:
		return "", "", "", false, fmt.Errorf("%s has a damaged generated block, so aw left it alone → restore the <!-- aw:begin and <!-- aw:end --> lines, or delete the block", path)
	}
	return text[:b], strings.Trim(text[b+len(begin):e], "\n"), text[e+len(end):], true, nil
}

func render(content string) string { return begin + "\n" + content + "\n" + end }

// splice puts the content in text's block, or appends a block when it has none.
func splice(text, content, path string) (string, error) {
	before, _, after, found, err := findBlock(text, path)
	if err != nil {
		return "", err
	}
	if found {
		return before + render(content) + after, nil
	}
	if text == "" {
		return render(content) + "\n", nil
	}
	return strings.TrimRight(text, "\n") + "\n\n" + render(content) + "\n", nil
}

func recorded(owner string) string {
	data, _ := os.ReadFile(filepath.Join(owner, managedPath))
	for _, line := range strings.Split(string(data), "\n") {
		if f := strings.Fields(line); len(f) == 2 && f[1] == managedKey {
			return f[0]
		}
	}
	return ""
}

// record stores the block's hash in .aw/managed, so a later hand edit can be told from a change in
// what aw generates.
func record(owner, hash string) (bool, error) {
	path := filepath.Join(owner, managedPath)
	data, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return false, err
	}
	next := withHash(string(data), managedKey, hash)
	if next == string(data) {
		return false, nil
	}
	return true, write(path, next)
}

func write(path, text string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(text), 0o644)
}

func read(path string) (string, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return "", nil
	}
	return string(data), err
}

// Apply composes the instructions. It is safe to rerun, and it changes only its own block.
func Apply(ctx context.Context, owner, name, namespace string) ([]Result, error) {
	agents, err := applyAgents(owner, name)
	if err != nil {
		return nil, err
	}
	out := []Result{agents}
	claude, err := applyImport(owner)
	if err != nil {
		return out, err
	}
	out = append(out, claude)
	personal, err := applyPersonal(ctx, owner, namespace)
	if err != nil {
		return out, err
	}
	return append(out, personal), nil
}

func applyAgents(owner, name string) (Result, error) {
	res := Result{Path: AgentsPath}
	path := filepath.Join(owner, AgentsPath)
	content, err := body(owner)
	if err != nil {
		return res, err
	}
	text, err := read(path)
	if err != nil {
		return res, err
	}
	_, inner, _, found, err := findBlock(text, AgentsPath)
	if err != nil {
		return res, err
	}
	if found && inner != content {
		if want := recorded(owner); want != "" && sum(inner) != want {
			res.Edited, res.Note = true, EditedNote
			return res, nil
		}
	}
	if text == "" {
		text = "# " + name + "\n"
	}
	next, err := splice(text, content, AgentsPath)
	if err != nil {
		return res, err
	}
	if next != text || !found {
		res.Changed = true
		if err := write(path, next); err != nil {
			return res, err
		}
	}
	changed, err := record(owner, sum(content))
	res.Changed = res.Changed || changed
	return res, err
}

func applyImport(owner string) (Result, error) {
	res := Result{Path: ClaudePath}
	path := filepath.Join(owner, ClaudePath)
	text, err := read(path)
	if err != nil {
		return res, err
	}
	if text == "" {
		return res, nil // no file: Claude Code reads AGENTS.md directly
	}
	for _, line := range strings.Split(text, "\n") {
		if strings.TrimSpace(line) == ClaudeImport {
			return res, nil
		}
	}
	res.Changed = true
	if text != "" && !strings.HasSuffix(text, "\n") {
		text += "\n"
	}
	return res, write(path, text+ClaudeImport+"\n")
}

// applyPersonal keeps the personal layer in the file Claude Code reads for it, which Git is told to
// ignore through info/exclude, so nothing about it appears in the team repository. A harness without
// such a file gets the personal layer in its session-start context instead (S13).
func applyPersonal(ctx context.Context, owner, namespace string) (Result, error) {
	res := Result{Path: PersonalPath}
	personal, err := read(config.PersonalInstructions(namespace))
	if err != nil {
		return res, err
	}
	content := strings.TrimSpace(personal)
	path := filepath.Join(owner, PersonalPath)
	text, err := read(path)
	if err != nil {
		return res, err
	}
	before, _, after, found, err := findBlock(text, PersonalPath)
	if err != nil {
		return res, err
	}
	if content == "" && !found {
		return res, nil
	}
	if _, err := run.In(owner).Run(ctx, "ls-files", "--error-unmatch", "--", PersonalPath); err == nil {
		return res, fmt.Errorf("%s is committed in the workspace repository, so personal instructions cannot go there without changing the team's files → remove it from Git, or ask the team to", PersonalPath)
	}
	if err := exclude(owner, "/"+PersonalPath); err != nil {
		return res, err
	}
	next := ""
	switch {
	case content != "":
		// Claude Code stops reading AGENTS.md by itself once this file exists, so it is imported here.
		if next, err = splice(text, ClaudeImport+"\n\n"+content, PersonalPath); err != nil {
			return res, err
		}
	default: // the personal file has gone: its block goes too, and whatever else is there stays
		next = strings.TrimSpace(before+after) + "\n"
		if next == "\n" {
			res.Changed = true
			return res, os.Remove(path)
		}
	}
	if next == text {
		return res, nil
	}
	res.Changed = true
	return res, write(path, next)
}

func exclude(owner, pattern string) error {
	if !workspace.IsGitRepo(owner) {
		return nil
	}
	common, err := workspace.GitCommonDir(owner)
	if err != nil {
		return err
	}
	path := filepath.Join(common, "info", "exclude")
	text, err := read(path)
	if err != nil {
		return err
	}
	for _, line := range strings.Split(text, "\n") {
		if strings.TrimSpace(line) == pattern {
			return nil
		}
	}
	if text != "" && !strings.HasSuffix(text, "\n") {
		text += "\n"
	}
	return write(path, text+pattern+"\n")
}

// Drift says how AGENTS.md's block differs from what aw would write: "" when it matches.
func Drift(owner string) (status string) {
	content, err := body(owner)
	if err != nil {
		return "unreadable: " + err.Error()
	}
	text, err := read(filepath.Join(owner, AgentsPath))
	if err != nil {
		return "unreadable: " + err.Error()
	}
	_, inner, _, found, err := findBlock(text, AgentsPath)
	switch {
	case err != nil:
		return "damaged"
	case !found:
		return "missing"
	case inner == content:
		return ""
	case recorded(owner) != "" && sum(inner) != recorded(owner):
		return "edited"
	}
	return "stale"
}

// CopyPersonal gives a new lane the owner's personal file: a lane is its own worktree, and the file
// is not in Git. It is best effort, because a lane works without it.
func CopyPersonal(owner, laneRoot string) {
	data, err := os.ReadFile(filepath.Join(owner, PersonalPath))
	if err != nil {
		return
	}
	_ = os.WriteFile(filepath.Join(laneRoot, PersonalPath), data, 0o644)
}

//go:embed skills/*.md
var skillFiles embed.FS

// Skills are the framework's onboarding skills, by name.
var Skills = []string{"workspace-design", "readiness-audit"}

// ApplySkills composes the skills into each harness's own format. Grok reads Claude Code's. A file
// edited by hand is left alone, and listed.
// take lists files to replace even though they differ from aw's record (aw upgrade --take), whether
// they were edited or never recorded.
func ApplySkills(owner string, take ...string) (changed []string, edited []string, err error) {
	for _, name := range Skills {
		data, err := skillFiles.ReadFile("skills/" + name + ".md")
		if err != nil {
			return nil, nil, err
		}
		for _, target := range skillTargets(name) {
			path := filepath.Join(owner, filepath.FromSlash(target))
			sum := sha256.Sum256(data)
			hash := hex.EncodeToString(sum[:])
			have, readErr := os.ReadFile(path)
			if readErr == nil {
				haveSum := sha256.Sum256(have)
				current := hex.EncodeToString(haveSum[:])
				if current == hash {
					continue
				}
				if current != recordedHash(owner, target) && !slices.Contains(take, target) {
					edited = append(edited, target)
					continue
				}
			}
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				return nil, nil, err
			}
			if err := os.WriteFile(path, data, 0o644); err != nil {
				return nil, nil, err
			}
			if err := recordHash(owner, target, hash); err != nil {
				return nil, nil, err
			}
			changed = append(changed, target)
		}
	}
	return changed, edited, nil
}

func skillTargets(name string) []string {
	return []string{
		".claude/skills/aw-" + name + "/SKILL.md",
		".agents/skills/aw-" + name + "/SKILL.md",
		".opencode/commands/aw-" + name + ".md",
	}
}

// SkillPaths are the files ApplySkills writes, relative to the owner checkout.
func SkillPaths() []string {
	var out []string
	for _, name := range Skills {
		out = append(out, skillTargets(name)...)
	}
	return out
}

func recordedHash(owner, key string) string {
	data, _ := os.ReadFile(filepath.Join(owner, managedPath))
	for _, line := range strings.Split(string(data), "\n") {
		if f := strings.Fields(line); len(f) == 2 && f[1] == key {
			return f[0]
		}
	}
	return ""
}

func recordHash(owner, key, hash string) error {
	path := filepath.Join(owner, managedPath)
	data, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return os.WriteFile(path, []byte(withHash(string(data), key, hash)), 0o644)
}

// withHash sets a key's hash in the managed list, in place, so that a file that has not changed is
// written back byte for byte.
func withHash(text, key, hash string) string {
	var out []string
	done := false
	for _, line := range strings.Split(strings.TrimRight(text, "\n"), "\n") {
		if line == "" {
			continue
		}
		if f := strings.Fields(line); len(f) == 2 && f[1] == key {
			if !done {
				out = append(out, hash+"  "+key)
				done = true
			}
			continue
		}
		out = append(out, line)
	}
	if !done {
		out = append(out, hash+"  "+key)
	}
	return strings.Join(out, "\n") + "\n"
}
