package runners

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"reflect"
	"strings"
	"testing"

	"github.com/connor981332/agent-workspace/internal/config"
)

func TestGeneratedOverlayPreservesProjectAndRegenerates(t *testing.T) {
	for _, initialize := range []string{`"echo original"`, `["sh", "-c", "echo original"]`, `{"first":"echo one","second":["echo","two"]}`} {
		t.Run(initialize, func(t *testing.T) {
			dir := t.TempDir()
			alias := filepath.Join(t.TempDir(), "checkout-alias")
			if err := os.Symlink(dir, alias); err != nil {
				t.Fatal(err)
			}
			dev := filepath.Join(dir, ".devcontainer")
			if err := os.MkdirAll(dev, 0o755); err != nil {
				t.Fatal(err)
			}
			source := []byte(`{
    // unknown fields and command forms must survive relocation
    "name": "Project configuration",
    "dockerComposeFile": "compose.yaml",
    "service": "app",
    "workspaceFolder": "/workspaces/project",
    "initializeCommand": ` + initialize + `,
    "remoteEnv": {"EXAMPLE": "value"},
    "customizations": {"vscode": {"extensions": ["example.extension"]}},
    "features": {"./local": {"version": "1"}, "ghcr.io/example/feature:1": {}},
    "forwardPorts": [3000, "3100", "app:3200", "db:3000", 5432],
    "portsAttributes": {"3000": {"label": "App", "onAutoForward": "openBrowser"}, "5432": {"label": "Database"}},
   }`)
			root := filepath.Join(dev, "devcontainer.json")
			if err := os.WriteFile(root, source, 0o644); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(filepath.Join(dev, "compose.yaml"), []byte("name: existing-stack\nservices:\n  app: {}\n"), 0o644); err != nil {
				t.Fatal(err)
			}
			cfg, err := config.LoadBytes(filepath.Join(dir, "workspace.toml"), []byte(`[workspace]
name = "Solo"
namespace = "solo"
schema = 1
[projects.solo]
directory = "."
runner = "devcontainer"
[projects.solo.servers.app]
command = "exec app --port {port}"
port = 3000
`))
			if err != nil {
				t.Fatal(err)
			}
			load := func() *Devcontainer {
				t.Helper()
				d, err := NewDevcontainer(cfg, alias, "solo", t.TempDir())
				if err != nil {
					t.Fatal(err)
				}
				if err := d.WriteFragment(); err != nil {
					t.Fatal(err)
				}
				return d
			}
			d := load()
			if d.Compose != "existing-stack" {
				t.Fatalf("Compose name changed: %s", d.Compose)
			}
			var got, original map[string]any
			if err := json.Unmarshal(stripJSONC(d.overlay), &got); err != nil {
				t.Fatal(err)
			}
			if err := json.Unmarshal(stripJSONC(source), &original); err != nil {
				t.Fatal(err)
			}
			for _, key := range []string{"workspaceFolder", "initializeCommand", "remoteEnv", "customizations"} {
				if !reflect.DeepEqual(got[key], original[key]) {
					t.Errorf("%s changed: %v != %v", key, got[key], original[key])
				}
			}
			if got["name"] != "Project configuration (aw)" {
				t.Errorf("picker name: %v", got["name"])
			}
			wantFiles := []any{filepath.Join(d.Dir, ".devcontainer", "compose.yaml"), filepath.Join(d.Dir, ".devcontainer", "aw", Fragment)}
			if !reflect.DeepEqual(got["dockerComposeFile"], wantFiles) {
				t.Errorf("Compose files: %v", got["dockerComposeFile"])
			}
			if !reflect.DeepEqual(got["forwardPorts"], []any{"db:3000", float64(5432)}) {
				t.Errorf("forwardPorts: %v", got["forwardPorts"])
			}
			attrs := got["portsAttributes"].(map[string]any)
			if attrs["3000"].(map[string]any)["label"] != "App" || attrs["3000"].(map[string]any)["onAutoForward"] != "ignore" || attrs["5432"].(map[string]any)["label"] != "Database" {
				t.Errorf("port attributes: %v", attrs)
			}
			features := got["features"].(map[string]any)
			if features["../local"] == nil || features["ghcr.io/example/feature:1"] == nil {
				t.Errorf("local feature not relocated: %v", features)
			}
			unchanged, err := os.ReadFile(root)
			if err != nil || !bytes.Equal(unchanged, source) {
				t.Fatal("project configuration was changed")
			}
			exclude, err := os.ReadFile(filepath.Join(dir, ".git", "info", "exclude"))
			if err != nil || !strings.Contains(string(exclude), ".devcontainer/aw/\n") {
				t.Fatalf("generated directory not excluded: %s, %v", exclude, err)
			}
			// An unrelated existing configuration is protected, including before fragment changes.
			if err := os.WriteFile(filepath.Join(dir, GeneratedConfig), []byte("project-owned"), 0o644); err != nil {
				t.Fatal(err)
			}
			if err := d.WriteFragment(); err == nil || !strings.Contains(err.Error(), "not generated by aw →") {
				t.Fatalf("unowned configuration was not protected: %v", err)
			}
			if err := os.WriteFile(filepath.Join(dir, GeneratedConfig), []byte(generatedHeader+"stale"), 0o644); err != nil {
				t.Fatal(err)
			}
			again := load()
			restored, err := os.ReadFile(filepath.Join(dir, GeneratedConfig))
			if err != nil || !bytes.Equal(restored, d.overlay) || again.hash != d.hash {
				t.Fatal("generated output was not regenerated stably")
			}
		})
	}
}
